ANDROID_PREFIX = "android.permission."


def _build_catalog() -> dict[str, Permission]:
    """One lookup table keyed by the full permission name."""
    catalog = {ANDROID_PREFIX + short: Permission("Android", *info) for short, info in _ANDROID.items()}
    catalog.update({name: Permission("Android", *info) for name, info in _ANDROID_FULL_NAMES.items()})
    catalog.update({name: Permission("iOS", *info) for name, info in _IOS.items()})
    return catalog


CATALOG = _build_catalog()
