"""
Plain-language explanations of common Android and iOS app permissions.

This is a fixed list written by hand rather than generated by Claude: the
meaning of a permission doesn't change from app to app, so a curated list is
free, instant and gives the same answer every time. Permissions not in the list
are shown as "not in our list yet" instead of guessed at.

Risk levels describe what the permission could expose if misused:
  High:   very personal data or control (messages, microphone, precise location,
          contacts, health, controlling other apps).
  Medium: personal but more limited data (camera, photos, approximate location).
  Low:    little personal data (internet access, notifications, vibration).
"""

from typing import NamedTuple


class Permission(NamedTuple):
    platform: str     # "Android" or "iOS"
    title: str        # short plain-language name
    explanation: str  # one or two sentences, no jargon
    risk_level: str   # "Low", "Medium" or "High"


